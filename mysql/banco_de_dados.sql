CREATE PROCEDURE sp_inserir_movimento_financeiro(
    IN p_descricao VARCHAR(255),
    IN p_id_cliente INT,
    IN p_pagrec VARCHAR(1),
    IN p_data_emissao DATE,
    IN p_valor_documento DECIMAL(19,2),
    IN p_id_categoria INT,
    IN p_observacao VARCHAR(255),
    IN p_id_veiculo INT, -- Pode passar NULL
    IN p_qtd_parcelas INT
)
BEGIN
    DECLARE v_id_mov INT;
    DECLARE v_i INT DEFAULT 1;
    DECLARE v_valor_parc DECIMAL(19,2);
    DECLARE v_vencimento DATE;

    -- Garante rollback em caso de qualquer exceção SQL
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
    END;

    START TRANSACTION;

    -- 1. Insere o Cabeçalho
    INSERT INTO MOVIMENTO_FINANCEIRO (DESCRICAO, ID_CLIENTE, PAGREC, DATA_EMISSAO, VALOR_DOCUMENTO, ID_CATEGORIA, OBSERVACAO, ID_VEICULO)
    VALUES (p_descricao, p_id_cliente, p_pagrec, p_data_emissao, p_valor_documento, p_id_categoria, p_observacao, p_id_veiculo);

    -- 2. Resgata o ID gerado isolado nesta transação
    SET v_id_mov = LAST_INSERT_ID();
    SET v_valor_parc = ROUND(p_valor_documento / p_qtd_parcelas, 2);

    -- 3. Loop nativo do MySQL para criar cada parcela
    WHILE v_i <= p_qtd_parcelas DO
        SET v_vencimento = DATE_ADD(p_data_emissao, INTERVAL (v_i - 1) MONTH);
        
        INSERT INTO MOVIMENTO_FINANCEIRO_PARCELAS (ID_FIN_MOV, PARCELA, DATA_VENCIMENTO, VALOR_PARCELA)
        VALUES (v_id_mov, v_i, v_vencimento, v_valor_parc);

        SET v_i = v_i + 1;
    END WHILE;

    COMMIT;
END //

